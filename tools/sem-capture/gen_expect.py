#!/usr/bin/python3
"""gen_expect: expect_spec.PATTERNS + the recorded corpus -> tests/fixtures/sem/expect.toml

  gen_expect.py [--fx tests/fixtures/sem] [--out tests/fixtures/sem/expect.toml]

Pure offline step (no browser, no bus). For every pattern and engine it looks up the fixture id in
<engine>/<page>.jsonl and records the raw evidence plus a status per expectation. Re-run after a
recapture; a diff of expect.toml then shows engine/version drift.
"""
import argparse
import json
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from expect_spec import PATTERNS  # noqa: E402

ENGINES = ("firefox", "chromium")
EVIDENCE_STATES = {"checked", "indeterminate", "pressed", "expanded", "expandable", "selected", "selectable",
                   "editable", "single-line", "multi-line", "required", "invalid-entry", "has-popup",
                   "modal", "horizontal", "vertical", "busy", "enabled", "focusable", "multiselectable",
                   "read-only", "checkable", "invalid"}


def load(fx, eng, page):
    p = os.path.join(fx, eng, page + ".jsonl")
    if not os.path.exists(p):
        return None
    rows = {}
    with open(p, encoding="utf-8") as f:
        hdr = json.loads(f.readline())
        for line in f:
            n = json.loads(line)
            if n.get("fixture_id") and n["fixture_id"] not in rows:
                rows[n["fixture_id"]] = n
    return hdr, rows


def q(s):
    return json.dumps(s, ensure_ascii=False)


def lst(xs):
    return "[" + ", ".join(q(x) for x in xs) + "]"


def main():
    ap = argparse.ArgumentParser()
    here = os.path.dirname(os.path.abspath(__file__))
    root = os.path.normpath(os.path.join(here, "..", ".."))
    ap.add_argument("--fx", default=os.path.join(root, "tests/fixtures/sem"))
    ap.add_argument("--out", default=None)
    a = ap.parse_args()
    out = a.out or os.path.join(a.fx, "expect.toml")
    cache, vers = {}, {}
    for pat in PATTERNS:
        for e in pat.get("engines", ENGINES):
            k = (e, pat["page"])
            if k not in cache:
                cache[k] = load(a.fx, e, pat["page"])
                if cache[k]:
                    vers[e] = (cache[k][0]["engine_version"], cache[k][0]["date"])
    L = ["# GENERATED by tools/sem-capture/gen_expect.py from tools/sem-capture/expect_spec.py and the",
         "# recorded corpus. Do not hand-edit: change expect_spec.py and rerun.",
         "# Per pattern: the CORRECT normalised result (role, tri-states, level, position, name source)",
         "# and, per engine, the raw AT-SPI evidence and whether it carries what the normaliser needs.",
         "# status: ok | missing-state | missing-attr | missing-node | role-differs.",
         "# disagree = true when the engines differ in raw role or in the evidence they export;",
         "# never_exported lists evidence one engine does not export at all (input to the",
         "# `inexpressible` rows, ADR-0024 s2.2).", "",
         "[corpus]"]
    for e, (v, d) in sorted(vers.items()):
        L.append("%s = %s" % (e, q("%s (captured %s)" % (v, d))))
    L.append("")
    stats = {"patterns": 0, "disagree": 0}
    never_all = {}
    for pat in PATTERNS:
        stats["patterns"] += 1
        obs = {}
        engs = pat.get("engines", ENGINES)
        for e in engs:
            c = cache[(e, pat["page"])]
            n = c[1].get(pat["id"]) if c else None
            if n is None:
                obs[e] = {"status": ["missing-node"]}
                continue
            states = set(n["states"])
            attrs = n["attrs"]
            st = []
            for s in pat.get("st", []):
                if s not in states:
                    st.append("missing-state:" + s)
            for s in pat.get("nst", []):
                if s in states:
                    st.append("unexpected-state:" + s)
            for k, v in pat.get("at", {}).items():
                if k not in attrs:
                    st.append("missing-attr:" + k)
                elif v != "*" and attrs[k] != v:
                    st.append("attr-value:%s=%s" % (k, attrs[k]))
            if pat.get("name") is not None and (n["name"] or "") != pat["name"]:
                st.append("name:%s" % (n["name"] or ""))
            obs[e] = {"role": n["role_name"], "raw_role": n["role"], "aria": attrs.get("xml-roles", ""),
                      "tag": attrs.get("tag", ""), "ev": sorted(states & EVIDENCE_STATES),
                      "attrs": {k: v for k, v in sorted(attrs.items())
                                if k not in ("id", "tag", "display", "class", "xml-roles", "explicit-name",
                                             "margin-left", "margin-right", "margin-top", "margin-bottom",
                                             "text-align", "text-indent", "line-number", "formatting")},
                      "name": n["name"] or "", "desc": n["desc"] or "", "ifaces": n["ifaces"],
                      "status": st or ["ok"]}
        present = [e for e in engs if "role" in obs[e]]
        disagree = len(present) == 2 and len(engs) == 2 and (obs["firefox"]["role"] != obs["chromium"]["role"]
                                          or obs["firefox"]["ev"] != obs["chromium"]["ev"]
                                          or set(obs["firefox"]["status"]) != set(obs["chromium"]["status"]))
        never = []
        for e in present:
            for s in obs[e]["status"]:
                if s.startswith("missing-attr:") or s.startswith("missing-state:"):
                    others = [o for o in present if o != e]
                    if others and s not in obs[others[0]]["status"]:
                        never.append("%s:%s" % (e, s.split(":", 1)[1]))
        # evidence missing in BOTH engines also counts: the fact is unexpressible over AT-SPI today
        both = (sorted(set(obs["firefox"]["status"]) & set(obs["chromium"]["status"]) - {"ok"})
                if len(engs) == 2 else [])
        if disagree:
            stats["disagree"] += 1
        for x in never:
            never_all.setdefault(x, []).append(pat["key"])
        L.append("[pattern.%s]" % q(pat["key"]))
        L.append("page = %s" % q(pat["page"]))
        L.append("fixture = %s" % q(pat["id"]))
        L.append("role = %s" % q(pat["role"]))
        for k in ("check", "press", "expand", "select"):
            if pat.get(k):
                L.append("%s = %s" % (k, q(pat[k])))
        if pat.get("level"):
            L.append("level = %d" % pat["level"])
        if pat.get("pos"):
            L.append("pos = [%d, %d]" % pat["pos"])
        if pat.get("name") is not None:
            L.append("name = %s" % q(pat["name"]))
        if pat.get("name_from"):
            L.append("name_from = %s" % q(pat["name_from"]))
        if pat.get("st"):
            L.append("need_states = %s" % lst(pat["st"]))
        if pat.get("nst"):
            L.append("forbid_states = %s" % lst(pat["nst"]))
        if pat.get("at"):
            L.append("need_attrs = {%s}" % ", ".join("%s = %s" % (q(k), q(v)) for k, v in pat["at"].items()))
        if pat.get("note"):
            L.append("note = %s" % q(pat["note"]))
        L.append("disagree = %s" % ("true" if disagree else "false"))
        if never:
            L.append("never_exported = %s" % lst(sorted(never)))
        if both:
            L.append("missing_in_both = %s" % lst(both))
        for e in engs:
            o = obs[e]
            L.append("[pattern.%s.%s]" % (q(pat["key"]), e))
            L.append("status = %s" % lst(o["status"]))
            if "role" in o:
                L.append("role = %s" % q(o["role"]))
                L.append("raw_role = %d" % o["raw_role"])
                L.append("aria_token = %s" % q(o["aria"]))
                L.append("tag = %s" % q(o["tag"]))
                L.append("states = %s" % lst(o["ev"]))
                L.append("ifaces = %s" % lst(o["ifaces"]))
                L.append("name = %s" % q(o["name"]))
                if o["desc"]:
                    L.append("desc = %s" % q(o["desc"]))
                L.append("attrs = {%s}" % ", ".join("%s = %s" % (q(k), q(v)) for k, v in o["attrs"].items()))
        L.append("")
    L.append("# never-exported summary (engine:evidence -> patterns)")
    for k, v in sorted(never_all.items()):
        L.append("# %s -> %s" % (k, ", ".join(v)))
    with open(out, "w", encoding="utf-8") as f:
        f.write("\n".join(L) + "\n")
    print("wrote %s: %s" % (out, stats), file=sys.stderr)


if __name__ == "__main__":
    main()
