#!/usr/bin/env bash
# Build the first-party plugins (plugins/*/Cargo.toml, target wasm32-wasip2) into plugins/dist/<id>/
# (manifest.toml + plugin.wasm) and regenerate plugins/pins.txt, the sha256 pin list the daemon
# compiles in (ADR-0026 section 2.7: a first-party package whose hash differs from its pin is
# refused). Run after changing a plugin, then rebuild the daemon.
#
#   . ./env.sh && tools/build-plugins.sh [plugin-dir-name ...]
set -euo pipefail
root="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
export CARGO_INCREMENTAL=0
tgt="${CARGO_TARGET_DIR:-/var/tmp/gorca-shared-target}/plugins-wasm"
dist="$root/plugins/dist"
mkdir -p "$dist"
names=("$@")
if [ ${#names[@]} -eq 0 ]; then
  for d in "$root"/plugins/*/; do
    [ -f "$d/Cargo.toml" ] && names+=("$(basename "$d")")
  done
fi
for n in "${names[@]}"; do
  src="$root/plugins/$n"
  id="$(sed -n 's/^id *= *"\(.*\)"/\1/p' "$src/manifest.toml" | head -n1)"
  crate="$(sed -n 's/^name *= *"\(.*\)"/\1/p' "$src/Cargo.toml" | head -n1)"
  (cd "$src" && CARGO_TARGET_DIR="$tgt" RUSTFLAGS="--remap-path-prefix=$root=/gorca" \
     cargo build --release --target wasm32-wasip2 --quiet)
  mkdir -p "$dist/$id"
  cp "$tgt/wasm32-wasip2/release/${crate//-/_}.wasm" "$dist/$id/plugin.wasm"
  cp "$src/manifest.toml" "$dist/$id/manifest.toml"
  # The message catalogs of the plugin's facts (not pinned: the installed directory is root's).
  rm -rf "$dist/$id/i18n"
  if [ -d "$src/i18n" ]; then cp -r "$src/i18n" "$dist/$id/i18n"; fi
  # The package is installed root-owned and read by the user's daemon: every directory and file
  # must be world-readable (an i18n directory left at 0750 silenced every message of the plugin).
  chmod -R u+rwX,go+rX,go-w "$dist/$id"
  echo "built $id"
done
{
  echo "# first-party plugin pins: <id> <sha256 of plugin.wasm>; generated by tools/build-plugins.sh"
  for m in "$dist"/*/manifest.toml; do
    d="$(dirname "$m")"
    id="$(sed -n 's/^id *= *"\(.*\)"/\1/p' "$m" | head -n1)"
    echo "$id $(sha256sum "$d/plugin.wasm" | cut -d' ' -f1)"
  done
} > "$root/plugins/pins.txt"
echo "pins: $root/plugins/pins.txt"
